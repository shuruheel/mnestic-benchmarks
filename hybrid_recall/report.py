"""Turn a results JSON into a markdown report (docs/RESULTS.md) and, optionally, plots."""

from __future__ import annotations

import json
from pathlib import Path

_CHECK = {True: "✅", False: "❌"}


def _fmt(x: float, nd: int = 2) -> str:
    return f"{x:.{nd}f}"


def render_markdown(payload: dict) -> str:
    meta = payload["meta"]
    env = payload["environment"]
    results = [r for r in payload["results"]]
    ok = [r for r in results if r["ok"]]
    failed = [r for r in results if not r["ok"]]

    lines: list[str] = []
    lines.append("# Benchmark Results\n")
    lines.append(
        "> Auto-generated by `hybrid-recall report`. Numbers are **hardware-specific** and "
        "reproducible via the command in [METHODOLOGY.md](METHODOLOGY.md). This file is "
        "overwritten on each report run.\n"
    )
    lines.append("## Run\n")
    lines.append(
        f"- **scale**: `{meta['name']}` — {meta['n_chunks']:,} chunks, "
        f"{meta['n_entities']:,} entities, {meta['n_edges']:,} edges, dim={meta['dim']}\n"
        f"- **queries**: {meta['n_queries']:,} | **k**: {meta['k']} | "
        f"pool_n: {meta['pool_n']} | graph_hops: {meta['graph_hops']} | rrf_k: {meta['rrf_k']}\n"
        f"- **embeddings**: {'real (sentence-transformers)' if meta['real_embeddings'] else 'synthetic, text-derived'} | seed: {meta['seed']}\n"
        f"- **environment**: {env['platform']} | Python {env['python']} | {env['processor']}\n"
        f"- **generated**: {payload['generated_at']}\n"
    )

    # --- main results table ---
    lines.append("\n## Results\n")
    lines.append(
        "| Engine | recall@{k} | p50 ms | p95 ms | p99 ms | QPS (1 thr) | build s | "
        "ingest rows/s | disk MB | query RSS MB | round-trips |".format(k=meta["k"])
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in sorted(ok, key=lambda r: -r["recall_at_k"]):
        lat = r["latency_ms"]
        lines.append(
            f"| **{r['engine']}** {r['version']} | {_fmt(r['recall_at_k'], 3)} | "
            f"{_fmt(lat.get('p50', 0))} | {_fmt(lat.get('p95', 0))} | {_fmt(lat.get('p99', 0))} | "
            f"{_fmt(r['qps_serial'], 0)} | {_fmt(r['build_seconds'])} | "
            f"{_fmt(r['ingest_rows_per_sec'], 0)} | {_fmt(r['disk_mb'], 1)} | "
            f"{_fmt(r['query_peak_rss_mb'], 0)} | {_fmt(r['avg_round_trips'], 1)} |"
        )
    if failed:
        lines.append("\n_Did not complete:_ " + ", ".join(f"`{r['engine']}` ({r['error']})" for r in failed))

    # --- capability matrix ---
    lines.append("\n## Capabilities\n")
    lines.append(
        "| Engine | Vector | Full-text | Graph | Native vec+FTS fusion | Fusion locus | "
        "Systems for all 3 signals | Embedded |"
    )
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in results:
        c = r["capabilities"]
        lines.append(
            f"| **{r['engine']}** | {_CHECK[c['vector']]} | {_CHECK[c['fts']]} | "
            f"{_CHECK[c['graph']]} | {_CHECK[c['native_fusion']]} | {c['fusion_locus']} | "
            f"{c['engines_needed']} | {_CHECK[c['embedded']]} |"
        )
    notes = [(r["engine"], r["capabilities"]["notes"]) for r in results if r["capabilities"].get("notes")]
    if notes:
        lines.append("")
        for eng, note in notes:
            lines.append(f"- **{eng}**: {note}")

    # --- native fusion highlight ---
    nat = [r for r in ok if r.get("native_fusion_latency_ms")]
    if nat:
        lines.append("\n## Native single-call fusion\n")
        lines.append(
            "One engine call that fuses signals internally (RRF inside the engine), vs the "
            "app-side fusion + separate queries the rest need. `signals` is how many of the "
            "three are fused in that one call. Recall here is measured against the **same "
            "oracle** as the main table — so when a 3-signal native call matches the decomposed "
            f"recall@{meta['k']} at a fraction of the latency, that is the integrated win.\n"
        )
        lines.append(f"| Engine | signals fused | native recall@{meta['k']} | p50 ms | p95 ms |")
        lines.append("|---|---|---|---|---|")
        for r in nat:
            nl = r["native_fusion_latency_ms"]
            rec = r.get("native_fusion_recall")
            rec_s = "—" if rec is None else _fmt(rec, 3)
            lines.append(
                f"| **{r['engine']}** | {r.get('native_fusion_signals', 2)} | {rec_s} | "
                f"{_fmt(nl.get('p50', 0))} | {_fmt(nl.get('p95', 0))} |"
            )

    # --- architecture axes: read-your-writes / consistency ---
    inc = [r for r in ok if r.get("n_incremental")]
    if inc:
        lines.append("\n## Architecture axes — where integration matters\n")
        lines.append(
            "Beyond raw recall/latency: an agent writes memories continuously, so the store "
            "must absorb a new memory and recall it **immediately**, keeping every signal "
            "consistent in one system. *Read-your-writes* = the fraction of just-upserted "
            "memories a freshly-issued probe finds, per signal — a signal whose index didn't "
            "update synchronously can't see the new memory. `n/a` = the engine lacks that "
            "signal entirely.\n"
        )
        lines.append(
            "| Engine | Transactional | Time-travel | Incremental index | Systems needed | "
            "upsert p50 ms | RYW vector | RYW full-text | RYW graph | **RYW fused** |"
        )
        lines.append("|---|---|---|---|---|---|---|---|---|---|")

        def _pct(x):
            return "n/a" if x is None else f"{x * 100:.0f}%"

        for r in inc:
            c = r["capabilities"]
            up = r["incremental_upsert_ms"].get("p50", 0)
            lines.append(
                f"| **{r['engine']}** | {_CHECK[c['transactional']]} | {_CHECK[c['time_travel']]} | "
                f"{_CHECK[c['incremental_index']]} | {c['engines_needed']} | {_fmt(up)} | "
                f"{_pct(r['freshness_vector'])} | {_pct(r['freshness_fts'])} | "
                f"{_pct(r['freshness_graph'])} | **{_pct(r['freshness_fused'])}** |"
            )
        lines.append(
            "\n*A low full-text RYW with high vector RYW means the engine's FTS index is a "
            "build-time snapshot: new memories are unsearchable by keyword until a rebuild, "
            "and the missing signal can drag the new memory out of the fused top-k entirely.*\n"
        )

    lines.append(
        "\n---\n*Recall is measured against an exact NumPy ground truth (full-scan cosine + "
        "exact BM25 + exact k-hop BFS, fused with the same canonical RRF). Engines missing a "
        "signal lose the recall that signal contributes — this is expected and is the point.*\n"
    )
    return "\n".join(lines)


def render_plots(payload: dict, out_dir: Path) -> list[Path]:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return []

    ok = [r for r in payload["results"] if r["ok"]]
    if not ok:
        return []
    out_dir.mkdir(parents=True, exist_ok=True)
    scale = payload["meta"]["name"]
    k = payload["meta"]["k"]
    paths: list[Path] = []

    names = [r["engine"] for r in ok]
    recalls = [r["recall_at_k"] for r in ok]
    p50s = [r["latency_ms"].get("p50", 0) for r in ok]

    # recall bar
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar(names, recalls, color="#4c72b0")
    ax.set_ylabel(f"recall@{k}")
    ax.set_ylim(0, 1.0)
    ax.set_title(f"Hybrid recall@{k} — {scale}")
    for i, v in enumerate(recalls):
        ax.text(i, v + 0.01, f"{v:.2f}", ha="center", fontsize=8)
    fig.tight_layout()
    p = out_dir / f"recall-{scale}.png"
    fig.savefig(p, dpi=120)
    plt.close(fig)
    paths.append(p)

    # recall vs latency pareto
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.scatter(p50s, recalls, color="#dd8452")
    for n, x, y in zip(names, p50s, recalls):
        ax.annotate(n, (x, y), fontsize=8, xytext=(4, 4), textcoords="offset points")
    ax.set_xlabel("p50 query latency (ms)")
    ax.set_ylabel(f"recall@{k}")
    ax.set_title(f"Recall vs latency — {scale}")
    fig.tight_layout()
    p = out_dir / f"recall-vs-latency-{scale}.png"
    fig.savefig(p, dpi=120)
    plt.close(fig)
    paths.append(p)
    return paths


def load_results(path: Path) -> dict:
    return json.loads(path.read_text())
